import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const p = await b.newPage();
p.on('pageerror', (e) => console.log('ERR', e.message));
await p.goto('http://127.0.0.1:4173/tools/bgm-preview.html');
await p.waitForFunction(() => window.wav, null, { timeout: 120000 });
console.log('peak', await p.evaluate(() => window.peak));
writeFileSync(process.argv[2] ?? 'bgm-preview.wav', Buffer.from(await p.evaluate(() => window.wav), 'base64'));
await b.close();
